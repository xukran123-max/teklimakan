class I18nManager {
  constructor() {
    let initialLang = 'ug';
    try {
      const urlParams = new URLSearchParams(window.location.search);
      const langParam = urlParams.get('lang');
      if (langParam && ['ug', 'tr', 'en'].includes(langParam)) {
        initialLang = langParam;
        localStorage.setItem('teklimakan_language', langParam);
      } else {
        initialLang = localStorage.getItem('teklimakan_language') || 'ug';
      }
    } catch (e) {
      initialLang = localStorage.getItem('teklimakan_language') || 'ug';
    }
    this.currentLang = initialLang;
    try {
      localStorage.setItem('teklimakan_currency_preference', initialLang === 'en' ? 'USD' : 'TRY');
    } catch (e) {}
  }

  getLang() {
    return this.currentLang;
  }

  setLang(lang) {
    if (['ug', 'tr', 'en'].includes(lang)) {
      this.currentLang = lang;
      localStorage.setItem('teklimakan_language', lang);

      // 💵 تىل بىلەن ماس قەدەمدە پۇل بىرلىكىنى ئاپتوماتىك ئالماشتۇرۇش:
      // ئۇيغۇرچە ۋە تۈركچە بولسا: لىرا (TRY)
      // ئىنگلىزچە بولسا: دوللار (USD)
      const targetCurrency = lang === 'en' ? 'USD' : 'TRY';
      try {
        localStorage.setItem('teklimakan_currency_preference', targetCurrency);
      } catch (e) {}
      if (window.appStore && typeof window.appStore.setCurrency === 'function') {
        window.appStore.setCurrency(targetCurrency);
      }

      // 🧠 2-3 قېتىملىق تىل زىيارەت خاتىرىسىگە ئاپتوماتىك قوشۇش
      if (window.TeklimakanPush && typeof window.TeklimakanPush.recordLanguageVisit === 'function') {
        window.TeklimakanPush.recordLanguageVisit(lang);
      }

      this.applyDirectionAndTypography();
      window.dispatchEvent(new CustomEvent('teklimakan_lang_changed', { detail: { lang, currency: targetCurrency } }));
    }
  }

  t(key, params = {}) {
    const dict = I18N_TRANSLATIONS[this.currentLang] || I18N_TRANSLATIONS['ug'];
    let text = dict[key] || I18N_TRANSLATIONS['ug'][key] || key;
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
    }
    return text;
  }

  getBrandName(brand) {
    if (!brand) return '';
    if (brand === 'بارلىق ماركىلار') return this.t('allBrands');
    const direct = BRAND_LOCALIZATIONS[brand];
    if (direct && direct[this.currentLang]) {
      return direct[this.currentLang];
    }
    for (const [key, map] of Object.entries(BRAND_LOCALIZATIONS)) {
      if (brand.includes(key) || key.includes(brand)) {
        return map[this.currentLang] || brand;
      }
    }
    // ئاپتوماتىك تەرجىمە قىلىش
    return this.autoTranslateUyghur(brand, this.currentLang);
  }

  getCategoryName(category) {
    if (!category) return '';
    if (category === 'all' || category === 'بارلىق مەھسۇلاتلار' || category === 'بارلىق تۈرلەر') {
      return this.t('allCategories');
    }
    const direct = CATEGORY_LOCALIZATIONS[category];
    if (direct && direct[this.currentLang]) {
      return direct[this.currentLang];
    }
    for (const [key, map] of Object.entries(CATEGORY_LOCALIZATIONS)) {
      if (category.includes(key) || key.includes(brandKeyClean(category))) {
        return map[this.currentLang] || category;
      }
    }
    return this.autoTranslateUyghur(category, this.currentLang);
  }

  getBadgeName(badge) {
    if (!badge) return '';
    const lang = this.currentLang;
    if (lang === 'ug') return badge;
    if (PROMO_BADGE_LOCALIZATIONS && PROMO_BADGE_LOCALIZATIONS[badge] && PROMO_BADGE_LOCALIZATIONS[badge][lang]) {
      return PROMO_BADGE_LOCALIZATIONS[badge][lang];
    }
    if (badge === 'ئەڭ قىزىق') return this.t('badgeHot');
    if (badge === 'ئېتىباردا') return this.t('badgeSale');
    if (badge === 'تەۋسىيە') return this.t('badgeFeatured');
    if (badge === 'يېڭى كەلگەن') return this.t('badgeNew');
    for (const [k, v] of Object.entries(PROMO_BADGE_LOCALIZATIONS || {})) {
      if (badge.includes(k) || k.includes(badge)) {
        return v[lang] || badge;
      }
    }
    return this.autoTranslateUyghur(badge, lang);
  }

  // 🛡️ سودىگەر ئىناۋەت دەرىجىسى بەلگىسىنى تەرجىمە قىلىش
  getReputationBadgeName(name, targetLang = null) {
    if (!name) return '';
    const lang = targetLang || this.currentLang;
    if (lang === 'ug') return name;
    if (REPUTATION_BADGE_LOCALIZATIONS && REPUTATION_BADGE_LOCALIZATIONS[name] && REPUTATION_BADGE_LOCALIZATIONS[name][lang]) {
      return REPUTATION_BADGE_LOCALIZATIONS[name][lang];
    }
    for (const [k, v] of Object.entries(REPUTATION_BADGE_LOCALIZATIONS || {})) {
      if (name.includes(k) || k.includes(name)) {
        return v[lang] || name;
      }
    }
    return this.autoTranslateUyghur(name, lang);
  }

  // 📦 تاۋار بىرلىكى (Unit) نى كۆپ تىلغا ئايلاندۇرۇش
  getUnitName(unit, targetLang = null) {
    if (!unit) return '';
    const lang = targetLang || this.currentLang;
    if (lang === 'ug') return unit;
    const clean = String(unit).trim().toLowerCase();
    for (const [k, v] of Object.entries(UNIT_LOCALIZATIONS || {})) {
      if (clean === k.toLowerCase() || clean === k) {
        return v[lang] || unit;
      }
    }
    for (const [k, v] of Object.entries(UNIT_LOCALIZATIONS || {})) {
      if (clean.includes(k.toLowerCase())) {
        return v[lang] || unit;
      }
    }
    return this.autoTranslateUyghur(unit, lang);
  }

  // ئەگەر ئۇيغۇرچە يېزىق قالغان بولسا تۈركچە ياكى ئىنگلىزچىگە ئاپتوماتىك دەل جايىدا تەرجىمە قىلىش
  autoTranslateUyghur(text, targetLang = null) {
    if (!text || typeof text !== 'string') return text;
    const lang = targetLang || this.currentLang;
    if (lang === 'ug') return text;

    // تېكىستتە ئۇيغۇرچە / ئەرەبچە ھەرپلەر بارمۇ؟
    const hasUyghurChar = /[\u0600-\u06FF]/.test(text);
    if (!hasUyghurChar) return text;

    let translated = text;

    // 1. بىۋاسىتە تۈرلەر، ماركىلار، ئىناۋەت بەلگىلىرى لۇغىتىدىن تەكشۈرۈش
    if (CATEGORY_LOCALIZATIONS[translated] && CATEGORY_LOCALIZATIONS[translated][lang]) {
      return CATEGORY_LOCALIZATIONS[translated][lang];
    }
    if (BRAND_LOCALIZATIONS[translated] && BRAND_LOCALIZATIONS[translated][lang]) {
      return BRAND_LOCALIZATIONS[translated][lang];
    }
    if (typeof REPUTATION_BADGE_LOCALIZATIONS !== 'undefined' && REPUTATION_BADGE_LOCALIZATIONS[translated] && REPUTATION_BADGE_LOCALIZATIONS[translated][lang]) {
      return REPUTATION_BADGE_LOCALIZATIONS[translated][lang];
    }
    if (typeof PROMO_BADGE_LOCALIZATIONS !== 'undefined' && PROMO_BADGE_LOCALIZATIONS[translated] && PROMO_BADGE_LOCALIZATIONS[translated][lang]) {
      return PROMO_BADGE_LOCALIZATIONS[translated][lang];
    }

    // 2. لۇغەت بويىچە ئالماشتۇرۇش
    UYGHUR_WORD_GLOSSARY.forEach(item => {
      if (translated.includes(item.ug)) {
        const replacement = item[lang] || item.tr;
        translated = translated.split(item.ug).join(replacement);
      }
    });

    // 3. يەنە ئۇيغۇرچە ھەرپ قېلىپ قالغان بولسا لاتىنچىغا تەلەپپۇز بويىچە ئايلاندۇرۇش
    if (/[\u0600-\u06FF]/.test(translated)) {
      translated = this.uyghurToLatin(translated, lang);
    }

    return translated.trim();
  }

  // ئۇيغۇرچىنى لاتىنچىغا ئەقلىي ئايلاندۇرۇش (Uyghur to Latin Phonetic Transliteration)
  uyghurToLatin(text, targetLang = 'tr') {
    if (!text || typeof text !== 'string') return text;
    
    return text.split(/(\s+|[.,!?:;"'()\-–—]+)/).map(segment => {
      if (!/[\u0600-\u06FF]/.test(segment)) return segment;
      
      let s = segment;
      // سوزۇق تاۋۇشلار
      s = s.replace(/ئۆ/g, 'Ö').replace(/ۆ/g, 'ö');
      s = s.replace(/ئۈ/g, 'Ü').replace(/ۈ/g, 'ü');
      s = s.replace(/ئې/g, 'E').replace(/ې/g, 'e');
      s = s.replace(/ئى/g, targetLang === 'tr' ? 'İ' : 'I').replace(/ى/g, 'i');
      s = s.replace(/ئا/g, 'A').replace(/ا/g, 'a');
      s = s.replace(/ئە/g, 'E').replace(/ە/g, 'e');
      s = s.replace(/ئو/g, 'O').replace(/و/g, 'o');
      s = s.replace(/ئۇ/g, 'U').replace(/ۇ/g, 'u');
      
      // ئۈزۈك تاۋۇشلار
      s = s.replace(/ب/g, 'b');
      s = s.replace(/پ/g, 'p');
      s = s.replace(/ت/g, 't');
      s = s.replace(/ج/g, targetLang === 'en' ? 'j' : 'c');
      s = s.replace(/چ/g, targetLang === 'en' ? 'ch' : 'ç');
      s = s.replace(/خ/g, targetLang === 'en' ? 'kh' : 'h');
      s = s.replace(/د/g, 'd');
      s = s.replace(/ر/g, 'r');
      s = s.replace(/ز/g, 'z');
      s = s.replace(/ژ/g, targetLang === 'en' ? 'zh' : 'j');
      s = s.replace(/س/g, 's');
      s = s.replace(/ش/g, targetLang === 'en' ? 'sh' : 'ş');
      s = s.replace(/غ/g, targetLang === 'en' ? 'gh' : 'g');
      s = s.replace(/ف/g, 'f');
      s = s.replace(/ق/g, targetLang === 'en' ? 'q' : 'k');
      s = s.replace(/ك/g, 'k');
      s = s.replace(/گ/g, 'g');
      s = s.replace(/ڭ/g, 'ng');
      s = s.replace(/ل/g, 'l');
      s = s.replace(/م/g, 'm');
      s = s.replace(/ن/g, 'n');
      s = s.replace(/ھ/g, 'h');
      s = s.replace(/ۋ/g, 'v');
      s = s.replace(/ي/g, 'y');
      s = s.replace(/ئ/g, '');

      // سۆزنىڭ باش ھەرپىنى چوڭايتىش
      if (s.length > 0) {
        s = s.charAt(0).toUpperCase() + s.slice(1);
      }
      return s;
    }).join('');
  }

  // تەرجىمە قىلىنالمىغان ھەر قانداق سۆز كۆرۈلسە، ئارقا بەتكە جىددىي ئۇقتۇرۇش قىلىپ سېلىش
  reportMissingTranslation(originalText, targetLang) {
    try {
      const STORAGE_NOTIF_KEY = 'teklimakan_missing_translations';
      let list = JSON.parse(localStorage.getItem(STORAGE_NOTIF_KEY)) || [];
      const exists = list.some(item => item.text === originalText && item.lang === targetLang);
      if (!exists) {
        list.push({
          id: 'TR-ERR-' + Date.now(),
          text: originalText,
          lang: targetLang,
          time: new Date().toLocaleString(),
          resolved: false
        });
        localStorage.setItem(STORAGE_NOTIF_KEY, JSON.stringify(list));
        window.dispatchEvent(new CustomEvent('uyghur_store_sync', { detail: { type: 'translation_missing' } }));
      }
    } catch (e) {}
  }

  isRTL() {
    return this.currentLang === 'ug';
  }

  applyDirectionAndTypography() {
    const html = document.documentElement;
    const isRtl = this.isRTL();
    html.setAttribute('dir', isRtl ? 'rtl' : 'ltr');
    html.setAttribute('lang', this.currentLang);

    if (isRtl) {
      document.body.classList.add('rtl-layout');
      document.body.classList.remove('ltr-layout');
    } else {
      document.body.classList.add('ltr-layout');
      document.body.classList.remove('rtl-layout');
    }
  }
}

